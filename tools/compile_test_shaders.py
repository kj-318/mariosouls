"""Compile the Remastered shaders with the system d3dcompiler_47.dll.

Writes, under framework/hosts/ds1remastered/:
  test_shaders_gen.h    from test_shaders.hlsl (injection test draw)
  render_shaders_gen.h  from the HLSL strings embedded in render_device.h
                        (worldVS, lineVS, screenVS, pixelPS), so the renderer
                        never compiles shaders inside the game process.
Compile errors are printed (and land in work/framework-build/last-build.txt).
Windows only; uses ctypes, no extra packages.
"""

import ctypes
import sys
from ctypes import wintypes
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOST = ROOT / "framework/hosts/ds1remastered"
SRC = HOST / "test_shaders.hlsl"
OUT = HOST / "test_shaders_gen.h"
RENDER_SRC = HOST / "render_device.h"
RENDER_OUT = HOST / "render_shaders_gen.h"
RENDER_SHADERS = [("worldVS", "vs_4_0", "kRenderWorldVS"), ("lineVS", "vs_4_0", "kRenderLineVS"),
                  ("screenVS", "vs_4_0", "kRenderScreenVS"), ("pixelPS", "ps_4_0", "kRenderPixelPS")]



# ID3DBlob: IUnknown (3) + GetBufferPointer (3) + GetBufferSize (4)
def blob_bytes(blob):
    vt = ctypes.cast(blob, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    get_ptr = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vt[3])
    get_size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vt[4])
    release = ctypes.WINFUNCTYPE(ctypes.c_ulong, ctypes.c_void_p)(vt[2])
    data = ctypes.string_at(get_ptr(blob), get_size(blob))
    release(blob)
    return data


def compile_one(compiler, source, entry, target, name=None):
    code = ctypes.c_void_p()
    errors = ctypes.c_void_p()
    hr = compiler(source, len(source), (name or str(SRC)).encode(), None, None, entry.encode(),
                  target.encode(), 0, 0, ctypes.byref(code),
                  ctypes.byref(errors))
    if errors.value:
        msg = blob_bytes(errors.value).decode(errors="replace")
        print(msg)
    if hr != 0 or not code.value:
        raise SystemExit("D3DCompile failed for %s (%s): hr=0x%08x" % (entry, target, hr & 0xFFFFFFFF))
    return blob_bytes(code.value)


def as_array(name, data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]))
    return "static const unsigned char %s[] = {\n%s,\n};\n" % (name, ",\n".join(rows))


def main():
    dll = ctypes.WinDLL("d3dcompiler_47.dll")
    compiler = dll.D3DCompile
    compiler.restype = ctypes.c_long
    compiler.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_void_p,
                         ctypes.c_void_p, ctypes.c_char_p, ctypes.c_char_p, wintypes.UINT,
                         wintypes.UINT, ctypes.POINTER(ctypes.c_void_p),
                         ctypes.POINTER(ctypes.c_void_p)]
    source = SRC.read_bytes()
    vs = compile_one(compiler, source, "VSMain", "vs_5_0")
    ps = compile_one(compiler, source, "PSMain", "ps_5_0")
    text = ("// Generated by tools/compile_test_shaders.py from test_shaders.hlsl - do not edit.\n"
            "#pragma once\n\n" + as_array("kTestVS", vs) + "\n" + as_array("kTestPS", ps))
    OUT.write_text(text, encoding="utf-8", newline="\r\n")
    print("Compiled test shaders: VS %d bytes, PS %d bytes -> %s" % (len(vs), len(ps), OUT))

    import re
    header = RENDER_SRC.read_text(encoding="utf-8")
    parts = ["// Generated by tools/compile_test_shaders.py from the HLSL in render_device.h - do not edit.\n"
             "#pragma once\n"]
    for var, target, array in RENDER_SHADERS:
        m = re.search(r'inline const char \*%s = R"HLSL\((.*?)\)HLSL";' % var, header, re.S)
        if not m:
            raise SystemExit("render_device.h: shader %s not found" % var)
        blob = compile_one(compiler, m.group(1).encode(), "main", target, "render_device.h:" + var)
        parts.append("\n" + as_array(array, blob))
        print("Compiled renderer %s (%s): %d bytes" % (var, target, len(blob)))
    RENDER_OUT.write_text("".join(parts), encoding="utf-8", newline="\r\n")


if __name__ == "__main__":
    sys.exit(main())
